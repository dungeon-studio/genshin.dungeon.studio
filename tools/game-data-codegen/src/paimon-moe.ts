import { writeFile } from 'node:fs/promises';

import { toKebabCase } from './slug.js';

const UPSTREAM_BANNERS =
  'https://raw.githubusercontent.com/MadeBaruna/paimon-moe/main/src/data/banners.js';

/** Resolves from `src/` and `dist/` alike, since both sit one level down. */
const RATE_UP_DATES_MODULE = new URL('../src/rate-up-dates.generated.ts', import.meta.url);

/** The fields of a paimon-moe character banner that dating reads. */
export interface Banner {
  /** Local time, `YYYY-MM-DD HH:mm:ss`. */
  start: string;
  /** Five-star rate-ups, as paimon-moe's snake_case ids. */
  featured: readonly string[];
  /** Four-star rate-ups, as paimon-moe's snake_case ids. */
  featuredRare: readonly string[];
}

function isStringArray(value: unknown): value is string[] {
  return Array.isArray(value) && value.every((item) => typeof item === 'string');
}

function isBanner(value: unknown): value is Banner {
  return (
    typeof value === 'object' &&
    value !== null &&
    'start' in value &&
    typeof value.start === 'string' &&
    'featured' in value &&
    isStringArray(value.featured) &&
    'featuredRare' in value &&
    isStringArray(value.featuredRare)
  );
}

/**
 * The character banners in an evaluated `banners.js`.
 *
 * @throws Error when upstream has reshaped the module, so a refresh fails
 *   rather than writing a partial table.
 */
export function toCharacterBanners(module: unknown): Banner[] {
  if (
    typeof module === 'object' &&
    module !== null &&
    'banners' in module &&
    typeof module.banners === 'object' &&
    module.banners !== null &&
    'characters' in module.banners &&
    Array.isArray(module.banners.characters)
  ) {
    const characters: unknown[] = module.banners.characters;
    if (characters.every(isBanner)) return characters;
  }
  throw new Error(`${UPSTREAM_BANNERS} no longer exports character banners in a known shape`);
}

/** The start date of each character's first rate-up banner, keyed by roster id. */
export function firstRateUps(banners: readonly Banner[]): Map<string, string> {
  const firstRateUp = new Map<string, string>();
  for (const banner of banners) {
    const date = banner.start.slice(0, 'YYYY-MM-DD'.length);
    for (const name of [...banner.featured, ...banner.featuredRare]) {
      const id = toKebabCase(name);
      const known = firstRateUp.get(id);
      if (!known || date < known) firstRateUp.set(id, date);
    }
  }
  return firstRateUp;
}

/** Quotes only the keys that need it, which is how Prettier leaves them. */
function toKey(id: string): string {
  return /^[a-z]\w*$/.test(id) ? id : `'${id}'`;
}

/** Renders the module text, separately from writing it, so it can be asserted on. */
export function renderRateUpDates(dates: ReadonlyMap<string, string>): string {
  const entries = [...dates]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([id, date]) => `  ${toKey(id)}: '${date}',`);

  // REUSE-IgnoreStart
  const header = [
    '// SPDX-FileCopyrightText: 2021 Made Baruna',
    '// SPDX-FileCopyrightText: 2026 Alex Brandt <alunduil@gmail.com>',
    '// SPDX-License-Identifier: MIT',
  ];
  // REUSE-IgnoreEnd

  return [
    ...header,
    '',
    "// Generated by @genshin/game-data-codegen from paimon-moe's banners.js",
    '// (https://github.com/MadeBaruna/paimon-moe). Do not edit by hand.',
    '// Regenerate with: pnpm --filter @genshin/game-data-codegen generate rate-up-dates',
    '',
    'export const FIRST_RATE_UP_DATES: Readonly<Record<string, string>> = {',
    ...entries,
    '};',
    '',
  ].join('\n');
}

/**
 * Rewrite `rate-up-dates.generated.ts` from paimon-moe's current banner data.
 * Returns the number of characters dated.
 *
 * Evaluates the fetched `banners.js`, which upstream publishes as a module
 * rather than as data.
 *
 * @throws Error when the fetch fails or upstream has reshaped the module.
 */
export async function generateRateUpDates(): Promise<number> {
  const response = await fetch(UPSTREAM_BANNERS);
  if (!response.ok) {
    throw new Error(
      `Fetching ${UPSTREAM_BANNERS} failed: ${response.status} ${response.statusText}`,
    );
  }
  const source = Buffer.from(await response.text()).toString('base64');
  const module: unknown = await import(`data:text/javascript;base64,${source}`);

  const dates = firstRateUps(toCharacterBanners(module));
  await writeFile(RATE_UP_DATES_MODULE, renderRateUpDates(dates));
  return dates.size;
}
